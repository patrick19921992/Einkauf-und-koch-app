// Geschätzte Preise für die Kostenschätzung beim automatischen Planen und in der Einkaufsliste.
// Keine Live-Preise: eigene Schätzwerte (Stand 10/2026), in der App immer als „≈ geschätzt“ gekennzeichnet.
// Wer genauere Preise kennt, trägt sie in der Einkaufsliste als eigenen Preis ein (gehen immer vor).
//
// Zeile: [schluessel, packPreisEuro, packMenge, einheit, optionen?]
//  - schluessel: wie postenSchluessel/zutatSchluessel ihn bilden (klein, Einzahl, mit Produkt-Zusatz nach
//    Komma, z. B. 'tomate, passiert'; das Komma darf auch fehlen). Was fehlt, findet findePreis über den
//    Schlüssel ohne Beschreibung vorne ('rote paprikaschote' → 'paprika') oder den Wortteil hinten.
//    Manche Wörter lässt zutatSchluessel in der Mehrzahl ('lasagneplatten', 'kekse') – dann steht es hier auch so.
//  - packPreisEuro: Preis einer Packung (bzw. von packMenge bei loser Ware), Discounter-Eigenmarke
//  - packMenge + einheit: 'g' | 'ml' | 'Stück' | Behälter-Einheit ('Bund', 'Packung', 'Scheibe', …)
//  - optionen: stueckGewicht (g je Stück), lose (nach Gewicht verkauft → keine ganzen Packungen),
//    dichte (g je ml, Standard 1), vorrat (Grundvorrat → kostet im Plan nichts),
//    container (Behälter, der genau einer Packung entspricht: 1 Dose = packMenge),
//    laeden (bekannter Packungspreis je Laden statt Ladenfaktor, z. B. { rewe: 1.49 })

